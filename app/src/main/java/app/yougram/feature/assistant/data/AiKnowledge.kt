    private fun norm(s: String) = s.lowercase().replace('ё', 'е')

    /** Подходящие записи по убыванию релевантности; пусто, если ничего не нашлось. */
    fun find(query: String, limit: Int = 2): List<Pair<Entry, Int>> {
        val t = norm(query)
        return entries.mapNotNull { en ->
            val score = en.keywords.maxOfOrNull { k ->
                if (k.split('+').all { t.contains(norm(it).trim()) }) k.replace("+", "").trim().length else 0
            } ?: 0
            if (score >= 3) en to score else null
        }.sortedByDescending { it.second }.take(limit)
    }

    private val infoStarts = listOf(
        "как ", "что ", "зачем", "почему", "где ", "какой", "какая", "какие", "какое", "можно ли", "расскажи", "объясни", "опиши",
        "а что", "для чего", "чем ", "сколько", "есть ли", "умеешь", "умеет", "кто ",
    )

    /** Похоже ли сообщение на вопрос/просьбу рассказать (а не на команду «включи …»). */
    fun isInfoQuery(query: String): Boolean {
        val t = norm(query).trim()
        return t.contains('?') || infoStarts.any { t.startsWith(it) } || t.contains("расскажи") || t.contains("объясни")
    }

    /** Короткая справка для системного промпта (≤ [maxChars] символов). */
    fun contextFor(query: String, maxChars: Int = 420): String {
        val best = find(query, 1).firstOrNull()?.first ?: return ""
        return " Справка: ${best.text}".take(maxChars)
    }

    /** Список разделов справки — для вопроса «что ты знаешь». */
    fun overview(): String =
        "Я знаю о MaterialGram: " + entries.joinToString(", ") { it.title.lowercase() } + ". Спросите о чём угодно из этого."
